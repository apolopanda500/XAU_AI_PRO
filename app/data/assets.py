def get_all_assets():
    return FOREX_ASSETS + CRYPTO_ASSETS + INDICES_ASSETS + COMMODITIES_ASSETS + STOCKS_ASSETS

def get_assets_by_category(category):
    category = category.lower()
    return [a for a in get_all_assets() if a.category.lower() == category]

def get_asset(symbol):
    symbol = symbol.upper()
    for asset in get_all_assets():
        if asset.symbol.upper() == symbol:
            return asset
    return None

def search_assets(query):
    query = query.upper().strip()
    if not query:
        return []
    return [a for a in get_all_assets() if query in a.symbol.upper() or query in a.name.upper()]

